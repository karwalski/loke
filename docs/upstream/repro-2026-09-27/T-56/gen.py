# gen.py N : N page modules p01..pNN (one function each) and repro.tk importing all of them,
# the shape of ooke's generated _handlers.tk registry.
import sys
N=int(sys.argv[1])
for i in range(1,N+1):
    open('p%02d.tk'%i,'w').write('m=p%02d;\nf=h():i64{ <%d };\n'%(i,i))
imps='\n'.join('i=a%02d:p%02d;'%(i,i) for i in range(1,N+1))
body='+'.join('a%02d.h()'%i for i in range(1,N+1))
open('repro.tk','w').write('''(* T-56: a module may import at most 32 others (TKC_MAX_IMPORTS).
   EXPECTED: a registry importing %d page modules compiles and prints their sum %d.
   DEFECT: compiler limit exceeded: too many imports (E9010). Generated by gen.py. *)
m=t56;
i=io:std.io;
%s
f=main():i64{
  io.println("sum=\\(%s)");
  <0
};
'''%(N,N*(N+1)//2,imps,body))
