#!/usr/bin/env python3
"""Derive docs/claims.md's Summary tables from its rows, and refuse a stale one.

Why this exists
---------------
The Summary was hand-maintained, and on 2026-09-23 it was wrong: four verdicts changed and
two rows were added in one session, and the table still read `verified 33 / total 95` while
the rows said 34 / 97. `check_claims.py` did not notice, because it checks that a verified
claim carries an evidence pointer and that every figure traces to metrics-baseline.md — not
that the register's own arithmetic adds up.

That is the same defect RV1.7 fixed for `docs/epics-and-stories.md`, and the same conclusion
applies: **a summary that is maintained by hand is a claim about the register that nothing
checks.** In a document whose entire purpose is to stop the project overstating itself, the
one table a reader is most likely to quote was the one with no evidence behind it.

So the tables are generated between sentinels, and `--check` fails if the file on disk does
not match what the rows imply.

    python3 scripts/gen_claims_summary.py --fix      # rewrite the tables from the rows
    python3 scripts/gen_claims_summary.py --check    # fail if they are stale
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
CLAIMS = REPO / "docs" / "claims.md"

VERDICTS = ("verified", "partial", "stub", "absent")
ROW_ID = re.compile(r"^[A-Z]+\d+$")
SECTION = re.compile(r"^## ([A-Z])\. (.+)$")

BEGIN = "<!-- BEGIN GENERATED SUMMARY -->"
END = "<!-- END GENERATED SUMMARY -->"


def anchor(letter: str, title: str) -> str:
    """GitHub's heading anchor for `## A. Some title — epic F3b`."""
    text = f"{letter}. {title}".lower()
    text = text.replace("—", "").replace("’", "")
    text = re.sub(r"[^a-z0-9 \-]", "", text)
    return "#" + text.strip().replace(" ", "-")


def collect() -> tuple[dict[str, int], list[tuple[str, str, dict[str, int], int]]]:
    totals = {v: 0 for v in VERDICTS}
    sections: list[tuple[str, str, dict[str, int], int]] = []
    cur = None
    for line in CLAIMS.read_text(encoding="utf-8").split("\n"):
        m = SECTION.match(line)
        if m:
            cur = (m.group(1), m.group(2), {v: 0 for v in VERDICTS}, 0)
            sections.append(cur)
            continue
        if not line.lstrip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 7 or not ROW_ID.match(cells[0]):
            continue
        verdict = cells[3].strip("`").strip().lower()
        if verdict not in VERDICTS:
            continue
        totals[verdict] += 1
        if cur is not None:
            cur[2][verdict] += 1
            sections[-1] = (cur[0], cur[1], cur[2], cur[3] + 1)
            cur = sections[-1]
    return totals, sections


def render() -> str:
    totals, sections = collect()
    out = [BEGIN, "", "| Verdict | Count |", "|---|---|"]
    for v in VERDICTS:
        out.append(f"| `{v}` | {totals[v]} |")
    out.append(f"| **Total** | **{sum(totals.values())}** |")
    out += ["", "By subsystem:", "",
            "| Subsystem | `verified` | `partial` | `stub` | `absent` | Rows |",
            "|---|---|---|---|---|---|"]
    for letter, title, counts, rows in sections:
        if rows == 0:
            continue
        out.append(f"| [{letter}. {title}]({anchor(letter, title)}) | "
                   f"{counts['verified']} | {counts['partial']} | {counts['stub']} | "
                   f"{counts['absent']} | {rows} |")
    out += ["",
            "*Generated by `scripts/gen_claims_summary.py` from the rows below. Do not edit "
            "by hand — the gate regenerates it and will disagree with you.*",
            "", END]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--fix", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args()

    text = CLAIMS.read_text(encoding="utf-8")
    wanted = render()

    if BEGIN not in text:
        if args.check:
            print(f"gen_claims_summary: FAIL — {CLAIMS.name} has no generated-summary "
                  f"sentinels. Run --fix once to install them.", file=sys.stderr)
            return 1
        # Install the sentinels around the two TABLES ONLY.
        #
        # The first version of this replaced everything between the "## Summary" heading and
        # the next "##", and that deleted 39 lines of analysis living under the same heading:
        # which verified rows are defended by a test, the two patterns that account for the
        # non-verified rows, and the standing notes on the browser request path and the audit
        # trail. It was caught by scripts/check_sweep_commit.py — the deletion was real and
        # the commit message did not mention it, which is the case that check exists for.
        #
        # So the sentinels are anchored on the tables themselves: from the "| Verdict | Count |"
        # header to the end of the subsystem table. A generator that rewrites prose it does not
        # understand is a worse bug than the stale numbers it was written to fix.
        i = text.index("| Verdict | Count |")
        j = text.index("\n\n", text.index("| Subsystem |", i))
        text = text[:i] + wanted + text[j:]
        CLAIMS.write_text(text, encoding="utf-8")
        print("gen_claims_summary: sentinels installed around the tables; prose untouched.")
        return 0

    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    if text[start:end] == wanted:
        print("gen_claims_summary: OK — the Summary matches the rows.")
        return 0
    if args.check:
        print("gen_claims_summary: FAIL — the Summary does not match the rows. "
              "Run `python3 scripts/gen_claims_summary.py --fix`.", file=sys.stderr)
        for a, b in zip(text[start:end].split("\n"), wanted.split("\n")):
            if a != b:
                print(f"    on disk: {a}\n    derived: {b}", file=sys.stderr)
        return 1
    CLAIMS.write_text(text[:start] + wanted + text[end:], encoding="utf-8")
    print("gen_claims_summary: Summary regenerated from the rows.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
